def extract_tree_names(tree_name):
    """
    استخراج هوشمند نام جنس و گونه از فرمت‌های پیچیده و ناقص
    """
    name = str(tree_name).strip()
    
    # جایگزینی اسپیس با آندرلاین برای یکدست شدن فرمت‌های مختلف
    name = name.replace(' ', '_')
    
    # حذف پیشوندها
    name = re.sub(r'^(cf|aff)[\._]+', '', name, flags=re.IGNORECASE)
    parts = [p for p in name.split('_') if p.strip()]
    
    # لیست کلماتی که نباید به عنوان "جنس" استخراج شوند
    ignore_words = ['uncultured', 'unidentified', 'nematoda', 'nematode', 'sp', 'cf']
    
    clean_parts = []
    for p in parts:
        clean_p = re.sub(r'[^a-zA-Z0-9\-]', '', p) # حذف علائم نگارشی
        if clean_p and clean_p.lower() not in ignore_words:
            clean_parts.append(clean_p)
            
    if not clean_parts:
        return "Unknown", ""
        
    raw_genus = clean_parts[0].lower()
    
    # مپ کردن گونه‌هایی که به اشتباه جای جنس نوشته شده‌اند به جنس اصلی
    species_to_genus_map = {
        'americanus': 'Necator',          # برای Necator americanus
        'briggsae': 'Caenorhabditis',     # برای Caenorhabditis briggsae
        'ratti': 'Strongyloides'          # برای Strongyloides ratti
    }
    
    if raw_genus in species_to_genus_map:
        genus = species_to_genus_map[raw_genus]
        species = raw_genus # کلمه اول در واقع اسم گونه بوده
    else:
        genus = raw_genus.split('-')[0].capitalize()
        species = clean_parts[1] if len(clean_parts) > 1 else "sp."
        
    # پاکسازی کلمات میانی
    if species.lower() in ['sp', 'aff', 'cf', 'nomen', 'group', 's']:
        species = clean_parts[2] if len(clean_parts) > 2 else ""
        
    return genus.capitalize(), species

