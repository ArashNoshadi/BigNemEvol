def export_for_r_analysis(tree, df_merged, output_dir):
    """
    آماده‌سازی و همگام‌سازی درخت و دیتافریم برای ورود به نرم‌افزار R
    (حذف گونه‌های اضافی از درخت و دیتافریم تا تناظر 1:1 ایجاد شود)
    """
    import copy
    r_export_dir = os.path.join(output_dir, "R_Analysis_Files")
    if not os.path.exists(r_export_dir):
        os.makedirs(r_export_dir)

    # کپی درخت برای جلوگیری از تغییر درخت اصلی
    pruned_tree = copy.deepcopy(tree)
    
    # استانداردسازی نام‌ها (تبدیل فاصله به آندرلاین)
