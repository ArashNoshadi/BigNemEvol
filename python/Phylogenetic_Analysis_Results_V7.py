def format_poly_equation(coeffs):
    """فرمت کردن دقیق ضرایب به شکل یک معادله قابل خواندن در مقالات"""
    degree = len(coeffs) - 1
    terms = []
    for i, c in enumerate(coeffs):
        power = degree - i
        if power == 0:
            terms.append(f"{c:.4e}")
        elif power == 1:
            terms.append(f"{c:.4e}x")
        else:
            terms.append(f"{c:.4e}x^{power}")
    eq = " + ".join(terms)
    return "y = " + eq.replace("+ -", "- ")

def calc_poly_stats(x, y, degree):
    """محاسبه ضرایب، رشته معادله، درصد R2 و مقادیر پیش‌بینی‌شده"""
    x_valid = np.array(x, dtype=float)
    y_valid = np.array(y, dtype=float)
    if len(x_valid) <= degree + 1:
        return None, None, np.nan, None
    try:
        coeffs = np.polyfit(x_valid, y_valid, degree)
        p = np.poly1d(coeffs)
        yhat = p(x_valid)
        ybar = np.sum(y_valid) / len(y_valid)
        sstot = np.sum((y_valid - ybar)**2)
        ssres = np.sum((y_valid - yhat)**2)
        r_squared = 1 - (ssres / sstot) if sstot != 0 else np.nan
        equation_str = format_poly_equation(coeffs)
        return coeffs, equation_str, r_squared * 100, yhat
    except:
        return None, None, np.nan, None

