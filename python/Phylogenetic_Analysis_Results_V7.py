def _to_percent_if_prob(x):
    try:
        xv = float(x)
        if 0 <= xv <= 1.0:
            return xv * 100.0
        return xv
    except:
        return np.nan

def _extract_numbers_from_string(s):
    if s is None:
        return []
    nums = re.findall(r"[-+]?\d*\.\d+|\d+", str(s))
    return [float(x) for x in nums] if nums else []

def get_supports_from_clade(clade):
    ab = np.nan
    sh = np.nan
    candidates = []
    if getattr(clade, 'name', None): candidates.append(clade.name)
    if getattr(clade, 'confidence', None): candidates.append(clade.confidence)
    if getattr(clade, 'comment', None): candidates.append(clade.comment)
    for cand in candidates:
        nums = _extract_numbers_from_string(cand)
        if not nums: continue
        if len(nums) >= 3:
            sh_candidate, ab_candidate = nums[0], nums[-1]
            return _to_percent_if_prob(ab_candidate), _to_percent_if_prob(sh_candidate)
        if len(nums) == 2:
            n1, n2 = nums[0], nums[1]
            p1, p2 = _to_percent_if_prob(n1), _to_percent_if_prob(n2)
            if 0 <= n1 <= 1 and n2 > 1: return p1, p2
            if 0 <= n2 <= 1 and n1 > 1: return p2, p1
            if abs(p1 - 100.0) < abs(p2 - 100.0): return p2, p1
            return p1, p2
        if len(nums) == 1:
            return np.nan, _to_percent_if_prob(nums[0])
    return np.nan, np.nan

def get_supports_from_ancestors(tree, leaf, max_depth=MAX_SUPPORT_SEARCH_DEPTH):
    cur = leaf
    depth = 0
    ab_val, sh_val = None, None
    while depth < max_depth:
        try: path = tree.get_path(cur)
        except Exception: break
        parent = path[-2] if len(path) >= 2 else None
        if parent is None: break
        s_ab, s_sh = get_supports_from_clade(parent)
        if pd.notna(s_ab) and (ab_val is None or pd.isna(ab_val)): ab_val = s_ab
        if pd.notna(s_sh) and (sh_val is None or pd.isna(sh_val)): sh_val = s_sh
        if (ab_val is not None and not pd.isna(ab_val)) and (sh_val is not None and not pd.isna(sh_val)): break
        cur = parent
        depth += 1
    return (ab_val if ab_val is not None else np.nan, sh_val if sh_val is not None else np.nan)

def leaf_passes_thresholds(tree, leaf, sh_thr=SH_THRESHOLD, ab_thr=AB_THRESHOLD, max_search_depth=MAX_SUPPORT_SEARCH_DEPTH):
    ab, sh = get_supports_from_ancestors(tree, leaf, max_depth=max_search_depth)
    if pd.isna(ab) or pd.isna(sh): return False, ab, sh
    try:
        passes = (float(sh) >= float(sh_thr)) and (float(ab) >= float(ab_thr))
        return bool(passes), ab, sh
    except:
        return False, ab, sh

