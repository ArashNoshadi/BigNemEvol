def check_clade_monophyly(tree, clade_dict):
    """بررسی مونوپایلی و استخراج دقیق لیست گونه‌ها برای اکسل"""
    report = ["=== Clade Monophyly / Paraphyly Analysis ==="]
    clade_data = [] 
    
    for clade_name, genera_list in clade_dict.items():
        target_leaves = []
        for leaf in tree.get_terminals():
            genus, _ = extract_tree_names(leaf.name)
            if genus.lower() in [g.lower() for g in genera_list]:
                target_leaves.append(leaf)
        
        if len(target_leaves) < 2:
            report.append(f"- {clade_name}: Not enough taxa (Found: {len(target_leaves)}).")
            clade_data.append({
                'Clade_Name': clade_name, 'Status': 'Not Enough Taxa', 
                'Target_Count': len(target_leaves), 'Intruder_Count': 0,
                'Target_Taxa_Found': ', '.join([l.name for l in target_leaves]),
                'Intruder_Taxa': ''
            })
            continue
            
        is_mono = tree.is_monophyletic(target_leaves)
        if is_mono:
            report.append(f"- {clade_name}: MONOPHYLETIC ({len(target_leaves)} taxa).")
            clade_data.append({
                'Clade_Name': clade_name, 'Status': 'Monophyletic', 
                'Target_Count': len(target_leaves), 'Intruder_Count': 0,
                'Target_Taxa_Found': ', '.join([l.name for l in target_leaves]),
                'Intruder_Taxa': ''
            })
        else:
            # ---> اصلاح مهم: اضافه شدن ستاره برای جلوگیری از خطای Biopython <---
            mrca = tree.common_ancestor(*target_leaves)
            all_leaves_in_mrca = mrca.get_terminals()
            intruders = [l for l in all_leaves_in_mrca if l not in target_leaves]
            report.append(f"- {clade_name}: PARAPHYLETIC (Found {len(target_leaves)} targets, {len(intruders)} intruders).")
            clade_data.append({
                'Clade_Name': clade_name, 'Status': 'Paraphyletic/Polyphyletic', 
                'Target_Count': len(target_leaves), 'Intruder_Count': len(intruders),
                'Target_Taxa_Found': ', '.join([l.name for l in target_leaves]),
                'Intruder_Taxa': ', '.join([l.name for l in intruders])
            })
    
    df_clade = pd.DataFrame(clade_data)
    return "\n".join(report) + "\n\n", df_clade

def ancestral_state_reconstruction_and_plot(tree, df_merged, output_dir):
    """بازسازی صفات اجدادی و استخراج نقاط گذار تکاملی برای اکسل و رسم درخت در قالب PDF"""
    asr_tree = copy.deepcopy(tree)
    
    leaf_data = []
    transition_events = []
    
    # استخراج تمام برگ‌های درخت
    terminals = asr_tree.get_terminals()
    
    for leaf in terminals:
        # نکته دوم: استخراج مستقیم سبک زندگی از روی دیکشنری habitat بر اساس جنس
        genus, species = extract_tree_names(leaf.name)
        state = get_lifestyle_from_habitat(genus)
        
        leaf.lifestyle_state = {state} if state in ["Free-living", "Parasitic"] else {"Unknown"}
        
        if "Free-living" in leaf.lifestyle_state: leaf.color = "green"
        elif "Parasitic" in leaf.lifestyle_state: leaf.color = "red"
        else: leaf.color = "gray"
        leaf.is_transition = False 

    for clade in asr_tree.get_nonterminals(order='postorder'):
        child_states = [child.lifestyle_state for child in clade.clades if hasattr(child, 'lifestyle_state')]
        valid_states = [s for s in child_states if s != {"Unknown"}]
        
        if not valid_states:
            clade.lifestyle_state = {"Unknown"}
        else:
            intersection = set.intersection(*valid_states)
            if intersection:
                clade.lifestyle_state = intersection
            else:
                clade.lifestyle_state = set.union(*valid_states)
                
        if clade.lifestyle_state == {"Free-living"}: clade.color = "green"
        elif clade.lifestyle_state == {"Parasitic"}: clade.color = "red"
        elif "Free-living" in clade.lifestyle_state and "Parasitic" in clade.lifestyle_state: clade.color = "blue"
        else: clade.color = "gray"

    transitions_to_parasitism = 0
    for clade in asr_tree.get_nonterminals(order='preorder'):
        parent_state = clade.lifestyle_state
        for child in clade.clades:
            if hasattr(child, 'lifestyle_state'):
                child_state = child.lifestyle_state
                child.parent_state = parent_state
                
                is_trans = False
                if "Free-living" in parent_state and child_state == {"Parasitic"}:
                    transitions_to_parasitism += 1
                    is_trans = True
                    descendant_leaves = [l.name for l in child.get_terminals()]
                    transition_events.append({
                        'Event_ID': f"Transition_{transitions_to_parasitism}",
                        'Ancestor_State': ', '.join(parent_state),
                        'New_State': ', '.join(child_state),
                        'Affected_Taxa_Count': len(descendant_leaves),
                        'Descendant_Taxa': ', '.join(descendant_leaves)
                    })
                    
                if child.is_terminal():
                    leaf_data.append({
                        'Species': child.name,
                        'Current_Lifestyle': ', '.join(child_state),
                        'Immediate_Ancestor_Lifestyle': ', '.join(parent_state),
                        'Direct_Evolutionary_Shift': "Yes (Free-living -> Parasitic)" if is_trans else "No"
                    })

    report = f"=== Ancestral State Reconstruction: Lifestyle ===\n"
    report += f"Estimated independent origins of Parasitism: {transitions_to_parasitism} times.\n\n"

    # نکته اول: محاسبه داینامیک طول تصویر برای جلوگیری از در هم رفتن اسم‌ها (حدود 0.15 اینچ به ازای هر گونه)
    dynamic_height = max(15, len(terminals) * 0.15)
    
    fig, ax = plt.subplots(figsize=(10, dynamic_height))
    Phylo.draw(asr_tree, axes=ax, do_show=False, branch_labels=None, label_func=lambda x: x.name if x.is_terminal() else "")
    ax.set_title("Ancestral State Reconstruction: Lifestyle\nGreen=Free-living, Red=Parasitic, Blue=Transition", fontweight='bold')
    
    g_patch = mpatches.Patch(color='green', label='Free-living')
    r_patch = mpatches.Patch(color='red', label='Parasitic')
    b_patch = mpatches.Patch(color='blue', label='Transitional / Ambiguous')
    ax.legend(handles=[g_patch, r_patch, b_patch], loc='upper left') # محل لجند را بالا بردیم تا روی درخت نیفتد
    
    # ذخیره فقط به صورت PDF با کیفیت بالا و فاصله مناسب
    if not os.path.exists(output_dir):
        os.makedirs(output_dir)
    pdf_path = os.path.join(output_dir, "Combined_Ancestral_State_Tree.pdf")
    fig.savefig(pdf_path, format='pdf', bbox_inches='tight')
    plt.close(fig)
    print(f"Saved: Combined_Ancestral_State_Tree.pdf in {output_dir}")
    
    return report, pd.DataFrame(leaf_data), pd.DataFrame(transition_events)


def get_lifestyle_from_habitat(genus_name):
    """
    استخراج سبک زندگی بر اساس دیکشنری. 
    اگر تگ free_living داشت -> Free-living، در غیر این صورت -> Parasitic
    """
    g = str(genus_name).strip().lower()
    
    # پیدا کردن جنس در دیکشنری هابیتات
    habitat_set = None
    for k, v in nematode_genera_by_habitat.items():
        if k.lower() == g:
            habitat_set = v
            break
            
    if not habitat_set:
        return "Unknown"
        
    habitat_str = "".join(list(habitat_set)).lower()
    
    # اعمال شرط درخواستی
    if "free_living" in habitat_str:
        return "Free-living"
    else:
        # تمام تگ‌های دیگر (animal_associated, plant_associated, aquatic_associated و...)
        return "Parasitic"
    

def get_node_depths(tree):
    """پیش‌پردازش برای محاسبه سریع عمق گره‌ها در درخت"""
    depths = {tree.root: 0}
    for clade in tree.find_clades(order='preorder'):
        for child in clade.clades:
            depths[child] = depths[clade] + 1
    return depths

def get_topological_distance(leaf1, leaf2, depths, tree):
    """محاسبه فاصله توپولوژیک (تعداد گره‌های بین دو گونه)"""
    mrca = tree.common_ancestor(leaf1, leaf2)
    return (depths[leaf1] - depths[mrca]) + (depths[leaf2] - depths[mrca])

def auto_detect_misplaced_taxa(tree, multiplier=3.0, min_node_separation=8):
    """
    الگوریتم هوشمند و تخصصی شناسایی Rogue Taxa بر اساس توپولوژی (Topology).
    """
    misplaced_taxa = []
    genus_dict = {}

    # 1. استخراج و گروه‌بندی بر اساس جنس
    for leaf in tree.get_terminals():
        # استخراج نام جنس (بخش اول اسم)
        clean_name = str(leaf.name).replace('(', '').replace("'", "")
        genus = clean_name.split('_')[0].lower().strip()
        genus_dict.setdefault(genus, []).append(leaf)

    # پیش‌محاسبه عمق تمام گره‌ها برای سرعت بخشیدن به پردازش
    depths = get_node_depths(tree)

    # 2. بررسی توپولوژی هر جنس
    for genus, leaves in genus_dict.items():
        # فقط جنس‌هایی که حداقل 3 گونه دارند بررسی می‌شوند
        if len(leaves) < 3:
            continue

        leaf_min_topo = {}
        for l1 in leaves:
            min_dist = float('inf')
            for l2 in leaves:
                if l1 != l2:
                    try:
                        dist = get_topological_distance(l1, l2, depths, tree)
                        if dist < min_dist:
                            min_dist = dist
                    except:
                        pass
            leaf_min_topo[l1] = min_dist

        # محاسبه میانه فواصل توپولوژیک در این جنس
        valid_dists = sorted(list(leaf_min_topo.values()))
        if not valid_dists:
            continue
            
        n = len(valid_dists)
        median_dist = (valid_dists[n//2] + valid_dists[-(n//2+1)]) / 2.0
        
        # 3. شناسایی گونه پرت (Rogue)
        for leaf, m_dist in leaf_min_topo.items():
            # شرط شناسایی گونه اشتباه:
            # الف) فاصله‌اش از نزدیکترین هم‌جنس خود، بسیار بیشتر از میانه گروه باشد
            # ب) حداقل باید X گره (مثلا 8 گره) با نزدیک‌ترین هم‌جنس خود فاصله داشته باشد تا واقعا در یک کلاد دیگر تلقی شود
            if m_dist >= (median_dist * multiplier) and m_dist >= min_node_separation:
                misplaced_taxa.append(leaf.name)

    return misplaced_taxa

